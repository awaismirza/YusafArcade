export type VersusMap = { name: string; map: string[] };
const V = (name: string, layout: string, spawns: [number, number][]): VersusMap => ({
  name,
  map: place(
    LAYOUTS[layout],
    spawns.map(([x, y], i) => [x, y, String(i + 1)] as [number, number, string]),
    true
  ),
});

