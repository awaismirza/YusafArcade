/** Puts characters onto a layout at (x, y) tile positions. */
function place(layout: string[], items: [number, number, string][], clearSpawns = false): string[] {
  const rows = layout.map((r) => (clearSpawns ? r.replace(/[1-4]/g, ".") : r).split(""));
  for (const [x, y, ch] of items) rows[y][x] = ch;
  return rows.map((r) => r.join(""));
}

export type Mission = { name: string; map: string[] };

const M = (name: string, layout: string, enemies: [number, number, string][]): Mission => ({ name, map: place(LAYOUTS[layout], enemies) });

